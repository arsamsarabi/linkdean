use chrono::{DateTime, Utc};
use std::collections::HashSet;
use uuid::Uuid;

use crate::{
    BookmarkExport, CategoryExport, CreateBookmark, CreateCategory, DashboardExport, Error,
    LinkdeanExport, Result,
};

/// The Linkdean JSON format this build writes.
pub const EXPORT_VERSION: u32 = 2;

#[derive(Debug, Default)]
pub struct ParsedImport {
    pub categories: Vec<CreateCategory>,
    /// Parallel to categories: temporary path key for nesting ("Folder/Sub")
    pub category_paths: Vec<String>,
    pub bookmarks: Vec<ParsedBookmark>,
    /// Dashboards from a Linkdean export. Pins name `ParsedBookmark::source_id` values.
    pub dashboards: Vec<DashboardExport>,
}

#[derive(Debug, Default)]
pub struct ParsedBookmark {
    pub bookmark: CreateBookmark,
    /// Folder paths (as in `category_paths`, without the parent part). Empty = unsorted.
    pub category_paths: Vec<String>,
    /// Id in the exported file, so its dashboards can point at this bookmark.
    pub source_id: Option<Uuid>,
    pub is_private: bool,
    pub created_at: Option<DateTime<Utc>>,
    pub updated_at: Option<DateTime<Utc>>,
}

impl ParsedBookmark {
    pub fn new(bookmark: CreateBookmark, category_path: Option<String>) -> Self {
        Self {
            bookmark,
            category_paths: category_path.into_iter().collect(),
            ..Default::default()
        }
    }
}

pub fn export_netscape(bookmarks: &[BookmarkExport], categories: &[CategoryExport]) -> String {
    let mut out = String::from(
        "<!DOCTYPE NETSCAPE-Bookmark-file-1>\n\
         <!-- Generated by Linkdean -->\n\
         <META HTTP-EQUIV=\"Content-Type\" CONTENT=\"text/html; charset=UTF-8\">\n\
         <TITLE>Bookmarks</TITLE>\n\
         <H1>Bookmarks</H1>\n\
         <DL><p>\n",
    );

    let exported: Vec<&CategoryExport> = categories.iter().filter(|c| !c.is_vault).collect();
    let known: HashSet<Uuid> = exported.iter().map(|c| c.id).collect();
    // A folder whose parent is not in the file (trashed, or someone else's) starts a tree.
    let roots = exported
        .iter()
        .filter(|c| c.parent_id.is_none_or(|p| !known.contains(&p)));
    for cat in roots {
        write_category_html(&mut out, cat, &exported, bookmarks, 1);
    }
    // A bookmark in no exported folder, such as one only in a shared folder, goes at the top.
    for b in bookmarks.iter().filter(|b| !b.is_vault) {
        if !b.all_category_ids().iter().any(|id| known.contains(id)) {
            write_bookmark_html(&mut out, b, 1);
        }
    }
    out.push_str("</DL><p>\n");
    out
}

fn write_category_html(
    out: &mut String,
    cat: &CategoryExport,
    all: &[&CategoryExport],
    bookmarks: &[BookmarkExport],
    depth: usize,
) {
    let pad = "    ".repeat(depth);
    out.push_str(&format!(
        "{pad}<DT><H3>{}</H3>\n{pad}<DL><p>\n",
        html_escape(&cat.name)
    ));
    for child in all.iter().filter(|c| c.parent_id == Some(cat.id)) {
        write_category_html(out, child, all, bookmarks, depth + 1);
    }
    // A bookmark in several folders appears in each.
    for b in bookmarks
        .iter()
        .filter(|b| !b.is_vault && b.all_category_ids().contains(&cat.id))
    {
        write_bookmark_html(out, b, depth + 1);
    }
    out.push_str(&format!("{pad}</DL><p>\n"));
}

fn write_bookmark_html(out: &mut String, b: &BookmarkExport, depth: usize) {
    let pad = "    ".repeat(depth);
    let tags = if b.tags.is_empty() {
        String::new()
    } else {
        format!(" TAGS=\"{}\"", html_escape(&b.tags.join(",")))
    };
    out.push_str(&format!(
        "{pad}<DT><A HREF=\"{}\"{tags}>{}</A>\n",
        html_escape(&b.url),
        html_escape(&b.title)
    ));
    if let Some(desc) = &b.description {
        out.push_str(&format!("{pad}<DD>{}\n", html_escape(desc)));
    }
}

/// Deeper trees are refused: folder paths grow with depth, so memory grows with its square.
const MAX_FOLDER_DEPTH: usize = 64;
const MAX_IMPORT_CATEGORIES: usize = 10_000;

fn too_deep() -> Error {
    Error::BadRequest(format!(
        "import nests folders more than {MAX_FOLDER_DEPTH} deep"
    ))
}

fn too_many_folders() -> Error {
    Error::BadRequest(format!(
        "import has more than {MAX_IMPORT_CATEGORIES} folders"
    ))
}

/// Refuse a parent chain that loops or runs too deep, before anything walks it.
fn check_category_tree(cats: &[CategoryExport]) -> Result<()> {
    if cats.len() > MAX_IMPORT_CATEGORIES {
        return Err(too_many_folders());
    }
    let parents: std::collections::HashMap<Uuid, Option<Uuid>> =
        cats.iter().map(|c| (c.id, c.parent_id)).collect();
    for c in cats {
        let mut parent = c.parent_id;
        let mut depth = 1;
        while let Some(id) = parent {
            depth += 1;
            if depth > MAX_FOLDER_DEPTH {
                return Err(too_deep());
            }
            parent = parents.get(&id).copied().flatten();
        }
    }
    Ok(())
}

pub fn parse_netscape(html: &str) -> Result<ParsedImport> {
    let mut parsed = ParsedImport::default();
    let mut stack: Vec<String> = Vec::new();
    let mut pending_folder: Option<String> = None;
    // `<DD>` describes the item just before it. Only a bookmark's is kept.
    let mut last_was_bookmark = false;

    for raw in html.lines() {
        let line = raw.trim();
        let lower = line.to_ascii_lowercase();

        if lower.starts_with("<dd>") {
            if last_was_bookmark {
                if let Some(last) = parsed.bookmarks.last_mut() {
                    let text = extract_inner_text(line);
                    if !text.is_empty() {
                        last.bookmark.description = Some(text);
                    }
                }
            }
            last_was_bookmark = false;
            continue;
        }
        let is_bookmark_line = lower.contains("<a ") && lower.contains("href=");
        if !is_bookmark_line {
            last_was_bookmark = false;
        }

        if lower.contains("<dl") {
            if let Some(name) = pending_folder.take() {
                if stack.len() >= MAX_FOLDER_DEPTH {
                    return Err(too_deep());
                }
                if parsed.categories.len() >= MAX_IMPORT_CATEGORIES {
                    return Err(too_many_folders());
                }
                let path = if stack.is_empty() {
                    name.clone()
                } else {
                    let parent = stack
                        .last()
                        .expect("stack non-empty when nesting folder path");
                    format!("{parent}/{name}")
                };
                let parent_path = stack.last().cloned();
                parsed.categories.push(CreateCategory {
                    name,
                    parent_id: None, // resolved later by path
                    is_hidden: false,
                    vault_id: None,
                    icon: None,
                });
                // stash parent path in category_paths as "path\0parent"
                let key = match parent_path {
                    Some(p) => format!("{path}\0{p}"),
                    None => path.clone(),
                };
                parsed.category_paths.push(key);
                stack.push(path);
            }
            continue;
        }

        if lower.starts_with("</dl") {
            stack.pop();
            pending_folder = None;
            continue;
        }

        if lower.contains("<h3") {
            pending_folder = Some(extract_inner_text(line));
            continue;
        }

        if is_bookmark_line {
            let url = attr_value(line, "href").unwrap_or_default();
            last_was_bookmark = false;
            if url.is_empty() {
                continue;
            }
            last_was_bookmark = true;
            let title = extract_inner_text(line);
            let tags = attr_value(line, "tags")
                .map(|t| {
                    t.split(',')
                        .map(|s| s.trim().to_string())
                        .filter(|s| !s.is_empty())
                        .collect()
                })
                .unwrap_or_default();
            let cat_path = stack.last().cloned();
            parsed.bookmarks.push(ParsedBookmark::new(
                CreateBookmark {
                    url,
                    title: Some(title),
                    description: None,
                    notes: None,
                    category_id: None,
                    category_ids: vec![],
                    tags,
                    ..Default::default()
                },
                cat_path,
            ));
        }
    }

    Ok(parsed)
}

pub fn parse_linkdean_json(raw: &str) -> Result<ParsedImport> {
    let export: LinkdeanExport =
        serde_json::from_str(raw).map_err(|e| Error::BadRequest(e.to_string()))?;
    if export.version > EXPORT_VERSION {
        return Err(Error::BadRequest(format!(
            "export version {} is newer than this server reads ({EXPORT_VERSION})",
            export.version
        )));
    }
    check_category_tree(&export.categories)?;
    let mut parsed = ParsedImport::default();

    // Sort so parents tend to come first
    let mut cats = export.categories;
    cats.sort_by_key(|c| c.parent_id.is_some());

    for c in &cats {
        let path = category_path_name(c, &cats);
        let parent_path = c
            .parent_id
            .and_then(|pid| cats.iter().find(|x| x.id == pid))
            .map(|p| category_path_name(p, &cats));
        let key = match &parent_path {
            Some(p) => format!("{path}\0{p}"),
            None => path.clone(),
        };
        parsed.categories.push(CreateCategory {
            name: c.name.clone(),
            parent_id: None,
            is_hidden: c.is_hidden,
            vault_id: None, // vault contents not exported plaintext
            icon: c.icon.clone(),
        });
        parsed.category_paths.push(key);
    }

    for b in export.bookmarks.into_iter().filter(|b| !b.is_vault) {
        let category_paths = b
            .all_category_ids()
            .iter()
            .filter_map(|cid| cats.iter().find(|c| c.id == *cid))
            .map(|c| category_path_name(c, &cats))
            .collect();
        parsed.bookmarks.push(ParsedBookmark {
            bookmark: CreateBookmark {
                url: b.url,
                title: Some(b.title),
                description: b.description,
                notes: b.notes,
                category_id: None,
                category_ids: vec![],
                tags: b.tags,
                is_favorite: b.is_favorite,
                is_unread: b.is_unread,
                is_pinned: b.is_pinned,
                ..Default::default()
            },
            category_paths,
            source_id: b.id,
            is_private: b.is_private,
            created_at: b.created_at,
            updated_at: b.updated_at,
        });
    }
    parsed.dashboards = export.dashboards;

    Ok(parsed)
}

pub fn parse_pocket_csv(raw: &str) -> Result<ParsedImport> {
    let mut parsed = ParsedImport::default();
    let mut rdr = csv::Reader::from_reader(raw.as_bytes());
    for row in rdr.records() {
        let row = row.map_err(|e| Error::BadRequest(e.to_string()))?;
        // title,url,time_added,tags,status
        let title = row.get(0).unwrap_or("").to_string();
        let url = row.get(1).unwrap_or("").to_string();
        if url.is_empty() {
            continue;
        }
        let tags = row
            .get(3)
            .unwrap_or("")
            .split('|')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect();
        parsed.bookmarks.push(ParsedBookmark::new(
            CreateBookmark {
                url,
                title: Some(if title.is_empty() {
                    "Untitled".into()
                } else {
                    title
                }),
                description: None,
                notes: None,
                category_id: None,
                category_ids: vec![],
                tags,
                ..Default::default()
            },
            None,
        ));
    }
    Ok(parsed)
}

pub fn parse_raindrop_csv(raw: &str) -> Result<ParsedImport> {
    let mut parsed = ParsedImport::default();
    let mut rdr = csv::Reader::from_reader(raw.as_bytes());
    let headers: Vec<String> = rdr
        .headers()
        .map_err(|e| Error::BadRequest(e.to_string()))?
        .iter()
        .map(|s| s.to_ascii_lowercase())
        .collect();

    let idx = |name: &str| headers.iter().position(|h| h == name);

    for row in rdr.records() {
        let row = row.map_err(|e| Error::BadRequest(e.to_string()))?;
        let url = idx("url")
            .or_else(|| idx("link"))
            .and_then(|i| row.get(i))
            .unwrap_or("")
            .to_string();
        if url.is_empty() {
            continue;
        }
        let title = idx("title")
            .and_then(|i| row.get(i))
            .unwrap_or("Untitled")
            .to_string();
        let folder = idx("folder")
            .or_else(|| idx("collection"))
            .and_then(|i| row.get(i))
            .filter(|s| !s.is_empty())
            .map(|s| s.to_string());
        if let Some(ref f) = folder {
            if !parsed
                .category_paths
                .iter()
                .any(|p| p == f || p.starts_with(&format!("{f}\0")))
            {
                parsed.categories.push(CreateCategory {
                    name: f.clone(),
                    parent_id: None,
                    is_hidden: false,
                    vault_id: None,
                    icon: None,
                });
                parsed.category_paths.push(f.clone());
            }
        }
        let tags = idx("tags")
            .and_then(|i| row.get(i))
            .unwrap_or("")
            .split(',')
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect();
        let note = idx("note")
            .or_else(|| idx("excerpt"))
            .and_then(|i| row.get(i))
            .map(|s| s.to_string());
        parsed.bookmarks.push(ParsedBookmark::new(
            CreateBookmark {
                url,
                title: Some(title),
                description: note,
                notes: None,
                category_id: None,
                category_ids: vec![],
                tags,
                ..Default::default()
            },
            folder,
        ));
    }
    Ok(parsed)
}

pub fn build_linkdean_export(
    categories: Vec<CategoryExport>,
    bookmarks: Vec<BookmarkExport>,
    dashboards: Vec<DashboardExport>,
) -> LinkdeanExport {
    LinkdeanExport {
        version: EXPORT_VERSION,
        exported_at: Utc::now(),
        categories,
        bookmarks,
        dashboards,
    }
}

fn category_path_name(c: &CategoryExport, all: &[CategoryExport]) -> String {
    let mut parts = vec![c.name.clone()];
    let mut parent = c.parent_id;
    while let Some(pid) = parent {
        if let Some(p) = all.iter().find(|x| x.id == pid) {
            parts.push(p.name.clone());
            parent = p.parent_id;
        } else {
            break;
        }
    }
    parts.reverse();
    parts.join("/")
}

fn attr_value(line: &str, name: &str) -> Option<String> {
    let lower = line.to_ascii_lowercase();
    let key = format!("{name}=");
    let idx = lower.find(&key)?;
    let rest = &line[idx + key.len()..];
    let quote = rest.chars().next()?;
    if quote != '"' && quote != '\'' {
        return None;
    }
    let end = rest[1..].find(quote)? + 1;
    Some(html_unescape(&rest[1..end]))
}

fn extract_inner_text(line: &str) -> String {
    let mut out = String::new();
    let mut in_tag = false;
    for ch in line.chars() {
        match ch {
            '<' => in_tag = true,
            '>' => in_tag = false,
            _ if !in_tag => out.push(ch),
            _ => {}
        }
    }
    html_unescape(out.trim())
}

fn html_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn html_unescape(s: &str) -> String {
    // `&amp;` goes last, or an escaped entity such as `&amp;lt;` would decode twice.
    s.replace("&lt;", "<")
        .replace("&gt;", ">")
        .replace("&quot;", "\"")
        .replace("&#39;", "'")
        .replace("&amp;", "&")
}

/// Resolve import category paths → created UUIDs (caller inserts cats in order).
pub fn path_key(path_entry: &str) -> (&str, Option<&str>) {
    match path_entry.split_once('\0') {
        Some((path, parent)) => (path, Some(parent)),
        None => (path_entry, None),
    }
}

pub fn leaf_name(path: &str) -> &str {
    path.rsplit('/').next().unwrap_or(path)
}

pub fn new_id() -> Uuid {
    Uuid::new_v4()
}

