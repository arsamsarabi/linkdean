        let html = r#"<DL><p>
<DT><A HREF="https://x.com/?a=1&amp;b=2" TAGS="r&amp;d,&lt;tools&gt;">Q &amp; A</A>
</DL>"#;
        let parsed = parse_netscape(html).unwrap();
