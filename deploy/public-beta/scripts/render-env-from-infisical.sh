#!/usr/bin/env bash
# Render Infisical /linkdean-public into the guest's Compose .env (restic keys filtered out).
#
# Runs on the Nova host (Infisical CLI + machine identity), not inside the guest.
#
# Usage:
#   LXC=linkdean-public bash deploy/public-beta/scripts/render-env-from-infisical.sh
#
# Auth: INFISICAL_TOKEN, or ~/.config/infisical/machine.env (Universal Auth), same as ncc.
# On Nova, secrets.arsam.app may not resolve; we fall back to the Infisical LAN bind.
set -euo pipefail

export PATH="${HOME}/.local/bin:/usr/local/bin:${PATH}"

LXC="${LXC:-linkdean-public}"
INFISICAL_ENV="${INFISICAL_ENV:-prod}"
INFISICAL_PATH="${INFISICAL_PATH:-/linkdean-public}"
GUEST_ENV="${GUEST_ENV:-/opt/linkdean/deploy/public-beta/.env}"
PROJECT_ID="${INFISICAL_PROJECT_ID:-}"
LAN_API_DEFAULT="${INFISICAL_LAN_URL:-http://192.168.0.120:8104}"

RESTIC_ONLY_KEYS='^(AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|B2_ENDPOINT|RESTIC_PASSWORD|RESTIC_BUCKET_LINKDEAN|RESTIC_KEEP_.*)$'

if ! command -v infisical >/dev/null 2>&1; then
  echo "infisical CLI not found (expected in PATH or ~/.local/bin)" >&2
  exit 1
fi
if ! command -v lxc >/dev/null 2>&1; then
  echo "lxc not found" >&2
  exit 1
fi

if [[ -z "${INFISICAL_API_URL:-}" ]]; then
  if getent hosts secrets.arsam.app >/dev/null 2>&1; then
    INFISICAL_API_URL="https://secrets.arsam.app"
  else
    INFISICAL_API_URL="$LAN_API_DEFAULT"
  fi
fi
export INFISICAL_API_URL
export INFISICAL_DISABLE_UPDATE_CHECK=true

if [[ -z "${INFISICAL_TOKEN:-}" && -f "${HOME}/.config/infisical/machine.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "${HOME}/.config/infisical/machine.env"
  set +a
  # Prefer LAN URL on Nova even if machine.env sets the public hostname.
  if ! getent hosts secrets.arsam.app >/dev/null 2>&1; then
    INFISICAL_API_URL="$LAN_API_DEFAULT"
    export INFISICAL_API_URL
  fi
  if [[ -n "${INFISICAL_CLIENT_ID:-}" && -n "${INFISICAL_CLIENT_SECRET:-}" ]]; then
    INFISICAL_TOKEN="$(infisical login --method=universal-auth \
      --client-id="$INFISICAL_CLIENT_ID" \
      --client-secret="$INFISICAL_CLIENT_SECRET" \
      --domain="$INFISICAL_API_URL" \
      --plain --silent)"
    export INFISICAL_TOKEN
  fi
  if [[ -n "${INFISICAL_PROJECT_ID:-}" && -z "$PROJECT_ID" ]]; then
    PROJECT_ID="$INFISICAL_PROJECT_ID"
  fi
fi

if [[ -z "${INFISICAL_TOKEN:-}" ]]; then
  echo "INFISICAL_TOKEN unset and ~/.config/infisical/machine.env missing/incomplete" >&2
  exit 1
fi

tmp="$(mktemp)"
filtered="$(mktemp)"
existing="$(mktemp)"
merged="$(mktemp)"
out="$(mktemp)"
trap 'rm -f "$tmp" "$filtered" "$existing" "$merged" "$out"' EXIT

echo "Exporting Infisical ${INFISICAL_ENV}${INFISICAL_PATH} via $INFISICAL_API_URL → ${LXC}:${GUEST_ENV}"
export_args=(export --path="$INFISICAL_PATH" --env="$INFISICAL_ENV" --format=dotenv --domain="$INFISICAL_API_URL")
if [[ -n "$PROJECT_ID" ]]; then
  export_args+=(--projectId="$PROJECT_ID")
fi
infisical "${export_args[@]}" >"$tmp"

# Merge: Infisical wins; keep guest-only keys (e.g. TUNNEL_TOKEN); drop restic-only keys.
if lxc exec "$LXC" -- test -f "$GUEST_ENV"; then
  lxc file pull "${LXC}${GUEST_ENV}" "$existing" >/dev/null
else
  : >"$existing"
fi

python3 - "$existing" "$tmp" "$merged" <<'PY'
import re
import sys
from pathlib import Path

RESTIC_ONLY = re.compile(
    r"^(AWS_ACCESS_KEY_ID|AWS_SECRET_ACCESS_KEY|B2_ENDPOINT|RESTIC_PASSWORD|RESTIC_BUCKET_LINKDEAN|RESTIC_KEEP_.*)$"
)

def load(path: Path) -> dict[str, str]:
    out: dict[str, str] = {}
    if not path.is_file():
        return out
    for line in path.read_text().splitlines():
        if not line or line.startswith("#") or "=" not in line:
            continue
        k, _, v = line.partition("=")
        k = k.strip()
        if not k or RESTIC_ONLY.match(k):
            continue
        if v == "" or v == "''" or v == '""':
            continue
        out[k] = v
    return out

existing, exported, dest = map(Path, sys.argv[1:4])
base = load(existing)
base.update(load(exported))
# Drop restic keys again in case they were already on the guest from a bad render.
base = {k: v for k, v in base.items() if not RESTIC_ONLY.match(k)}
if not base:
    raise SystemExit("Refusing to write an empty Compose .env")
dest.write_text("\n".join(f"{k}={v}" for k, v in sorted(base.items())) + "\n")
print(f"merged {len(base)} keys: {', '.join(sorted(base))}")
PY
{
  echo "# Generated by render-env-from-infisical.sh $(date -u +%Y-%m-%dT%H:%M:%SZ)"
  echo "# SoT: Infisical ${INFISICAL_ENV}${INFISICAL_PATH} (restic keys excluded; guest-only keys kept)"
  echo
  cat "$merged"
} >"$out"

lxc file push "$out" "${LXC}${GUEST_ENV}" --uid 0 --gid 0 --mode 0600
echo "Wrote ${LXC}:${GUEST_ENV}"
